/** Відповідь-ймовірність: нескоротний дріб, але приймаємо будь-який рівний запис (і десятковий). */
function vidpovidP(m: number, n: number) {
  return { vidpovid: vidpovidDrib(m, n).slice(0, 1), pokaz: `$${tvidpovidDrib(m, n, false)}$`, perevirka: rivnyiDrib(m, n) };
}

const KUBYK: [string, (k: number) => boolean][] = [
  ['парне число', (k) => k % 2 === 0],
  ['непарне число', (k) => k % 2 === 1],
  ['число, кратне 3', (k) => k % 3 === 0],
  ['просте число', (k) => [2, 3, 5].includes(k)],
  ['одиниця', (k) => k === 1],
  ['шістка', (k) => k === 6],
];

function kubyk(r: Vypadok): TrenZavdannia {
  let opys: string;
  let umova: (k: number) => boolean;
  if (r.shans(0.5)) [opys, umova] = r.vybir(KUBYK);
  else {
    const t = r.chyslo(1, 6);
    const typ = r.chyslo(0, 2);
    opys = typ === 0 ? `число, більше за ${t}` : typ === 1 ? `число, менше за ${t}` : `число, не менше за ${t}`;
    umova = typ === 0 ? (k) => k > t : typ === 1 ? (k) => k < t : (k) => k >= t;
  }
  const spryiatlyvi = [1, 2, 3, 4, 5, 6].filter(umova);
  const m = spryiatlyvi.length;
  return {
    pytannia: `Підкидають гральний кубик. Яка ймовірність, що випаде ${opys}? Запиши дробом через риску, наприклад 2/7.`,
    ...vidpovidP(m, 6),
    pidkazka: 'Усіх наслідків 6. Випиши ті, що підходять.',
    rozviazok: m === 0 ? 'Таких чисел на кубику немає: m = 0, P = 0 — подія неможлива.' : `Підходять: ${spryiatlyvi.join(', ')} — m = ${m}; P = ${m}/6${m === 6 ? ' = 1' : vidpovidDrib(m, 6)[0] !== `${m}/6` ? ` = ${vidpovidDrib(m, 6)[0]}` : ''}`,
  };
}

const KOLIORY: [string, string][] = [
  ['червоних', 'червона'],
  ['синіх', 'синя'],
  ['зелених', 'зелена'],
  ['жовтих', 'жовта'],
  ['білих', 'біла'],
];

function kulky(r: Vypadok): TrenZavdannia {
  const [k1, k2, k3] = r.rizni(3, 0, KOLIORY.length - 1).map((i) => KOLIORY[i]);
  const tryKolory = r.shans();
  const ch3 = [r.chyslo(1, 12), r.chyslo(1, 12), tryKolory ? r.chyslo(1, 9) : 0];
  const n = ch3[0] + ch3[1] + ch3[2];
  const ne = r.shans(0.3);
  const m = ne ? n - ch3[0] : ch3[0];
  const sklad = `${k1[0]} — ${ch3[0]}${tryKolory ? `, ${k2[0]} — ${ch3[1]} і ${k3[0]} — ${ch3[2]}` : ` і ${k2[0]} — ${ch3[1]}`}`;
  return {
    pytannia: `У коробці лежать кульки: ${sklad}. Навмання витягають одну. Яка ймовірність, що вона ${ne ? 'не ' : ''}${k1[1]}? Запиши дробом через риску.`,
    ...vidpovidP(m, n),
    pidkazka: `Усіх кульок: ${ch3.filter(Boolean).join(' + ')}. ${ne ? `Підходять усі, крім ${k1[0]}.` : ''}`,
    rozviazok: `n = ${n}, m = ${m}; P = ${m}/${n}${vidpovidDrib(m, n)[0] !== `${m}/${n}` ? ` = ${vidpovidDrib(m, n)[0]}` : ''}`,
  };
}

function lotereia(r: Vypadok): TrenZavdannia {
  for (;;) {
    const n = r.vybir([10, 20, 25, 40, 50, 100, 200, 500]);
    const m = r.chyslo(1, Math.min(Math.floor(n / 2), 60));
    const vids = (m * 100) / n;
    if (!Number.isInteger(vids)) continue;
    const prohrash = r.shans(0.3);
    return {
      pytannia: `Серед ${n} лотерейних білетів ${m} виграшних. Яка ймовірність ${prohrash ? 'не виграти' : 'виграти'}, купивши один білет? Відповідь дай у відсотках.`,
      vidpovid: prohrash ? 100 - vids : vids,
      odynytsi: '%',
      pidkazka: prohrash ? `Невиграшних білетів ${n} − ${m}.` : `P = ${m}/${n}; переведи у відсотки.`,
      rozviazok: prohrash ? `${n - m}/${n} · 100 % = ${100 - vids} %` : `${m}/${n} · 100 % = ${vids} %`,
    };
  }
}

function kartky(r: Vypadok): TrenZavdannia {
  for (;;) {
    const N = r.chyslo(10, 30);
    const k = r.chyslo(2, 7);
    const typ = r.chyslo(0, 1);
    const pidkhodiat = typ === 0 ? (x: number) => x % k === 0 : (x: number) => x > N - k * 2;
    const m = Array.from({ length: N }, (_, i) => i + 1).filter(pidkhodiat).length;
    if (m === 0 || m === N) continue;
    return {
      pytannia: `На ${N} картках написано числа від 1 до ${N}. Навмання беруть одну картку. Яка ймовірність, що на ній число, ${typ === 0 ? `кратне ${k}` : `більше за ${N - k * 2}`}? Запиши дробом через риску.`,
      ...vidpovidP(m, N),
      pidkazka: typ === 0 ? `Скільки чисел від 1 до ${N} діляться на ${k}?` : `Від ${N - k * 2 + 1} до ${N} — скільки це чисел?`,
      rozviazok: `n = ${N}, m = ${m}; P = ${m}/${N}${vidpovidDrib(m, N)[0] !== `${m}/${N}` ? ` = ${vidpovidDrib(m, N)[0]}` : ''}`,
    };
  }
}

function dviMonety(r: Vypadok): TrenZavdannia {
  const [opys, m, yaki] = r.vybir([
    ['на обох монетах випаде герб', 1, 'ГГ'],
    ['на обох монетах випаде число', 1, 'ЧЧ'],
    ['випаде рівно один герб', 2, 'ГЧ, ЧГ'],
    ['випаде хоча б один герб', 3, 'ГГ, ГЧ, ЧГ'],
    ['на монетах випаде різне', 2, 'ГЧ, ЧГ'],
    ['на монетах випаде однакове', 2, 'ГГ, ЧЧ'],
  ] as [string, number, string][]);
  return {
    pytannia: `Одночасно підкидають дві монети. Яка ймовірність, що ${opys}? Запиши дробом через риску.`,
    ...vidpovidP(m, 4),
    pidkazka: 'Випиши всі наслідки: ГГ, ГЧ, ЧГ, ЧЧ (Г — герб, Ч — число).',
    rozviazok: `Наслідків 4: ГГ, ГЧ, ЧГ, ЧЧ. Підходять: ${yaki} — m = ${m}; P = ${m}/4${m === 2 ? ' = 1/2' : ''}`,
  };
}

