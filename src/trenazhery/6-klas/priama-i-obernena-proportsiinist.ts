// Пряма й обернена пропорційність: одна величина зросла в k разів — друга теж у k разів (пряма) або
// зменшилася в k разів (обернена); задачі пропорцією; «ні та, ні інша» — коли немає «у скільки разів».
import { mnozh, type Henerator, type Vypadok, type TrenZavdannia } from '../dopomoha.ts';

const ZALEZHNOSTI = [
  { p: 'Кількість однакових зошитів і їхня вартість', v: 'пряма', ch: 'Удвічі більше зошитів — удвічі більша вартість.' },
  { p: 'Швидкість і час руху на тому самому шляху', v: 'обернена', ch: 'Їдеш удвічі швидше — витрачаєш удвічі менше часу.' },
  { p: 'Час руху і пройдений шлях при сталій швидкості', v: 'пряма', ch: 'Удвічі довше їдеш — удвічі більший шлях.' },
  { p: 'Кількість робітників і час, за який вони виконають ту саму роботу', v: 'обернена', ch: 'Удвічі більше робітників — удвічі менше часу.' },
  { p: 'Ціна одного олівця і кількість олівців, які можна купити за 100 грн', v: 'обернена', ch: 'Удвічі дорожчий олівець — удвічі менше олівців.' },
  { p: 'Сторона квадрата і його периметр', v: 'пряма', ch: 'Сторона більша вдвічі — периметр теж удвічі.' },
  { p: 'Вік людини і її зріст', v: 'ні та, ні інша', ch: 'Зріст росте, але не «у стільки ж разів», а з якогось віку взагалі не змінюється.' },
  { p: 'Маса цукру і кількість однакових пакетів, у які його розсипали порівну по 1 кг', v: 'пряма', ch: 'Удвічі більше цукру — удвічі більше пакетів.' },
  { p: 'Кількість кранів і час, за який вони наповнять той самий бак', v: 'обернена', ch: 'Удвічі більше кранів — удвічі швидше.' },
  { p: 'Номер дня місяця і температура повітря', v: 'ні та, ні інша', ch: 'Температура не залежить від номера дня «у стільки ж разів».' },
];

function vyd(r: Vypadok): TrenZavdannia {
  const z = r.vybir(ZALEZHNOSTI);
  return {
    pytannia: `${z.p} — яка це залежність?`,
    vidpovid: z.v,
    varianty: ['пряма', 'обернена', 'ні та, ні інша'],
    pidkazka: 'Збільш одну величину вдвічі. Що станеться з другою?',
    rozviazok: `${z.ch} Тож залежність ${z.v === 'ні та, ні інша' ? 'ні пряма, ні обернена' : z.v}.`,
  };
}

const PRIAMI = [
  { u: [20, 60], umova: (a: number, b: number, c: number) => `${a} кг яблук коштують ${b} грн. Скільки коштують ${c} кг таких яблук?`, od: 'грн' },
  { u: [40, 90], umova: (a: number, b: number, c: number) => `За ${a} год поїзд пройшов ${b} км. Скільки кілометрів він пройде за ${c} год з тією самою швидкістю?`, od: 'км' },
  { u: [2, 5], umova: (a: number, b: number, c: number) => `З ${a} кг яблук виходить ${b} л соку. Скільки літрів соку вийде з ${c} кг таких яблук?`, od: 'л' },
];

function priama(r: Vypadok): TrenZavdannia {
  const s = r.vybir(PRIAMI);
  const u = r.chyslo(s.u[0], s.u[1]);
  const [a, c] = r.rizni(2, 2, 9);
  return {
    pytannia: s.umova(a, u * a, c),
    vidpovid: u * c,
    odynytsi: s.od,
    pidkazka: `Залежність пряма: ${a} : ${c} = ${u * a} : x.`,
    rozviazok: `Пряма пропорційність: ${a} : ${c} = ${u * a} : x; x = ${u * a} · ${c} : ${a} = ${u * c}.`,
  };
}

const OBERNENI = [
  {
    umova: (a: number, b: number, c: number) =>
      `Зі швидкістю ${a} км/год автобус доїжджає до міста за ${b} год. За скільки годин він доїде зі швидкістю ${c} км/год?`,
    a: [40, 50, 60, 80, 90, 100, 120],
    od: 'год',
  },
  {
    umova: (a: number, b: number, c: number) =>
      `${a} ${mnozh(a, 'однаковий кран', 'однакові крани', 'однакових кранів')} наповнюють бак за ${b} хв. За скільки хвилин його наповнять ${c} ${mnozh(c, 'такий кран', 'такі крани', 'таких кранів')}?`,
    a: [2, 3, 4, 5, 6, 8, 10, 12],
    od: 'хв',
  },
  {
    umova: (a: number, b: number, c: number) =>
      `${a} ${mnozh(a, 'робітник', 'робітники', 'робітників')} виконують роботу за ${b} ${mnozh(b, 'день', 'дні', 'днів')}. За скільки днів цю роботу виконають ${c} ${mnozh(c, 'такий робітник', 'такі робітники', 'таких робітників')}?`,
    a: [2, 3, 4, 5, 6, 8, 10, 12],
  },
];

function obernena(r: Vypadok): TrenZavdannia {
  const s = r.vybir(OBERNENI);
  for (;;) {
    const [a, c] = r.rizni(2, 0, s.a.length - 1).map((i) => s.a[i]);
    const b = r.chyslo(2, 12);
    const x = (a * b) / c;
    if (!Number.isInteger(x) || x < 1) continue;
    return {
      pytannia: s.umova(a, b, c),
      vidpovid: x,
      odynytsi: s.od,
      pidkazka: `Залежність обернена: ${c > a ? 'більше' : 'менше'} → ${c > a ? 'менше' : 'більше'} часу. ${a} : ${c} = x : ${b}.`,
      rozviazok: `Обернена пропорційність: ${a} : ${c} = x : ${b}; x = ${a} · ${b} : ${c} = ${x}.`,
    };
  }
}

export default {
  rivni: ['пряма чи обернена', 'пряма пропорційність', 'обернена пропорційність'],
  zavdannia(r, riven) {
    if (riven === 1) return r.shans(0.7) ? vyd(r) : priama(r);
    if (riven === 2) return r.shans(0.75) ? priama(r) : vyd(r);
    return r.vybir([obernena, obernena, priama, vyd])(r);
  },
} satisfies Henerator;
