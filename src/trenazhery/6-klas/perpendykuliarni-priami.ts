// Перпендикулярні прямі (Істер § 44): перетинаються під прямим кутом, усі чотири кути по 90°; через точку — лише одна
// перпендикулярна пряма; сусідні кути при перетині — у сумі 180°; перпендикулярні промені: кут між OA і OC — 90°,
// тож промінь усередині ділить його на частини, а поза ним — додає.
import { type Henerator, type Vypadok, type TrenZavdannia } from '../dopomoha.ts';

const PRIAMI = ['a', 'b', 'c', 'm', 'n', 'k', 'p'];
const TAK_NI = ['так', 'ні'];

const ZHYTTIA = [
  { p: 'два сусідні краї аркуша паперу', v: 'так', ch: 'Краї аркуша сходяться під прямим кутом.' },
  { p: 'ніжка стола і підлога', v: 'так', ch: 'Ніжка стоїть під прямим кутом до підлоги.' },
  { p: 'стрілки годинника о 3:00', v: 'так', ch: 'О 3:00 між стрілками 90°.' },
  { p: 'стрілки годинника о 9:00', v: 'так', ch: 'О 9:00 між стрілками 90°.' },
  { p: 'стрілки годинника о 2:00', v: 'ні', ch: 'О 2:00 між стрілками 60° — не прямий кут.' },
  { p: 'стрілки годинника о 5:00', v: 'ні', ch: 'О 5:00 між стрілками 150° — не прямий кут.' },
  { p: 'дві рейки залізниці', v: 'ні', ch: 'Рейки взагалі не перетинаються.' },
  { p: 'стовп і рівна дорога', v: 'так', ch: 'Стовп ставлять під прямим кутом до дороги.' },
  { p: 'лінії «плюса» +', v: 'так', ch: 'Лінії «плюса» перетинаються під прямим кутом.' },
  { p: 'лінії «хрестика» ×, що перетинаються під кутом 60°', v: 'ні', ch: 'Кут 60° — не прямий.' },
];

function zhyttia(r: Vypadok): TrenZavdannia {
  const z = r.vybir(ZHYTTIA);
  return {
    pytannia: `Чи перпендикулярні лінії, які утворюють ${z.p}?`,
    vidpovid: z.v,
    varianty: TAK_NI,
    pidkazka: 'Чи перетинаються вони під прямим кутом?',
    rozviazok: z.ch,
  };
}

function zaKutom(r: Vypadok): TrenZavdannia {
  const [m, n] = r.rizni(2, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  const g = r.shans(0.4) ? 90 : r.krim(20, 160, [90]);
  return {
    pytannia: `Прямі $${m}$ і $${n}$ перетинаються, один із кутів між ними ${g}°. Чи перпендикулярні вони?`,
    vidpovid: g === 90 ? 'так' : 'ні',
    varianty: TAK_NI,
    pidkazka: 'Перпендикулярні — коли кут між прямими прямий, 90°.',
    rozviazok: g === 90 ? 'Кут 90° — прямі перпендикулярні.' : `Кут ${g}° не прямий — прямі не перпендикулярні.`,
  };
}

function kuty(r: Vypadok): TrenZavdannia {
  const [m, n] = r.rizni(2, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  if (r.shans(0.3)) {
    return {
      pytannia: `Прямі $${m}$ і $${n}$ перпендикулярні. Скільки градусів має кожен із чотирьох кутів, що утворилися?`,
      vidpovid: 90,
      odynytsi: '°',
      pidkazka: 'Перпендикулярні прямі утворюють чотири однакові кути.',
      rozviazok: '360° : 4 = 90° — усі кути прямі.',
    };
  }
  const g = r.krim(20, 160, [90]);
  return {
    pytannia: `Прямі $${m}$ і $${n}$ перетинаються, один із кутів між ними ${g}°. Знайди сусідній із ним кут.`,
    vidpovid: 180 - g,
    odynytsi: '°',
    pidkazka: 'Сусідні кути при перетині разом утворюють розгорнутий кут — 180°.',
    rozviazok: `180° − ${g}° = ${180 - g}°`,
  };
}

/** OA ⊥ OC; промінь OB усередині прямого кута чи поза ним. */
function promeni(r: Vypadok): TrenZavdannia {
  const g = r.chyslo(10, 80);
  const [A, B, C] = r.vybir([
    ['A', 'B', 'C'],
    ['M', 'K', 'N'],
    ['P', 'Q', 'R'],
  ]);
  if (r.shans(0.6)) {
    return {
      pytannia: `Промені $O${A}$ і $O${C}$ перпендикулярні, а промінь $O${B}$ проходить між ними. $\\angle ${A}O${B} = ${g}°$. Знайди $\\angle ${B}O${C}$.`,
      vidpovid: 90 - g,
      odynytsi: '°',
      pidkazka: `Кут ${A}O${C} прямий, а промінь O${B} ділить його на дві частини.`,
      rozviazok: `∠${A}O${C} = 90°, тож ∠${B}O${C} = 90° − ${g}° = ${90 - g}°`,
    };
  }
  return {
    pytannia: `Промені $O${A}$ і $O${C}$ перпендикулярні. Промінь $O${B}$ лежить поза кутом $${A}O${C}$, і $\\angle ${C}O${B} = ${g}°$. Знайди $\\angle ${A}O${B}$.`,
    vidpovid: 90 + g,
    odynytsi: '°',
    pidkazka: `Кут ${A}O${B} складається з прямого кута ${A}O${C} і кута ${C}O${B}.`,
    rozviazok: `∠${A}O${B} = 90° + ${g}° = ${90 + g}°`,
  };
}

const SKILKY = [
  { p: 'Скільки прямих, перпендикулярних до прямої {a}, можна провести через точку M, що не лежить на {a}?', v: '1', ch: 'Лише одну.' },
  { p: 'Скільки прямих, перпендикулярних до прямої {a}, можна провести через точку M, що лежить на {a}?', v: '1', ch: 'Лише одну.' },
  { p: 'Скільки прямих, що перетинають пряму {a}, можна провести через точку M, яка не лежить на {a}?', v: 'безліч', ch: 'Через M можна провести безліч прямих, що перетнуть {a}; але лише одна з них перпендикулярна до {a}.' },
  { p: 'Скільки прямих кутів утворюють дві перпендикулярні прямі?', v: '4', ch: 'Усі чотири кути при перетині — прямі.' },
];

function skilky(r: Vypadok): TrenZavdannia {
  const a = r.vybir(PRIAMI);
  const s = r.vybir(SKILKY);
  return {
    pytannia: s.p.replaceAll('{a}', a),
    vidpovid: s.v,
    varianty: ['1', '2', '4', 'безліч'],
    pidkazka: 'Намалюй пряму і точку і спробуй провести різні прямі.',
    rozviazok: s.ch.replaceAll('{a}', a),
  };
}

export default {
  rivni: ['перпендикулярні чи ні', 'кути при перетині', 'перпендикулярні промені, скільки прямих'],
  zavdannia(r, riven) {
    if (riven === 1) return r.shans() ? zhyttia(r) : zaKutom(r);
    if (riven === 2) return r.vybir([kuty, kuty, zaKutom])(r);
    return r.vybir([promeni, promeni, skilky, kuty])(r);
  },
} satisfies Henerator;
