function vyd(r: Vypadok): TrenZavdannia {
  const z = r.vybir(ZALEZHNOSTI);
  return {
    pytannia: `${z.p} — яка це залежність?`,
    vidpovid: z.v,
    varianty: ['пряма', 'обернена', 'ні та, ні інша'],
    pidkazka: 'Збільш одну величину вдвічі. Що станеться з другою — і чи рівно вдвічі?',
    rozviazok: `${z.ch} Тож залежність ${z.v === 'ні та, ні інша' ? 'ні пряма, ні обернена' : z.v}.`,
  };
}

function yakZminylas(r: Vypadok): TrenZavdannia {
  const k = r.chyslo(2, 9);
  const razy = mnozh(k, 'раз', 'рази', 'разів');
  const zbilsh = r.shans();
  const [tak, navpaky] = zbilsh ? ['збільшилося', 'зменшилося'] : ['зменшилося', 'збільшилося'];
  return {
    pytannia: `Значення однієї з двох обернено пропорційних величин ${tak} в ${k} ${razy}. Як змінилося значення другої?`,
    vidpovid: `${navpaky} в ${k} ${razy}`,
    varianty: r.peremishaty([`${navpaky} в ${k} ${razy}`, `${tak} в ${k} ${razy}`, `${navpaky} на ${k}`]),
    pidkazka: 'Обернено пропорційні змінюються в різні боки, але у стільки ж разів.',
    rozviazok: `Друга величина ${navpaky} в ${k} ${razy}: їхній добуток не змінюється.`,
  };
}

function dobutok(r: Vypadok): TrenZavdannia {
  for (;;) {
    const [a, c] = r.rizni(2, 2, 15);
    const b = r.chyslo(2, 20);
    if ((a * b) % c) continue;
    return {
      pytannia: `Величини x і y обернено пропорційні. Коли x = ${a}, y = ${b}. Знайди y, коли x = ${c}.`,
      vidpovid: (a * b) / c,
      pidkazka: `Добуток x · y сталий: ${a} · ${b}.`,
      rozviazok: `x · y = ${a} · ${b} = ${a * b}; y = ${a * b} : ${c} = ${(a * b) / c}.`,
    };
  }
}

/** Обернена задача: a → b, нове значення c → x = a · b : c. */
