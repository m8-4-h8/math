function priama(r: Vypadok): TrenZavdannia {
  const s = r.vybir(PRIAMI);
  const u = r.chyslo(s.u[0], s.u[1]);
  const [a, c] = r.rizni(2, 2, 9);
  return {
    pytannia: s.umova(a, u * a, c),
    vidpovid: u * c,
    odynytsi: s.od,
    pidkazka: `Спершу визнач залежність: ${c > a ? 'більше' : 'менше'} → ${c > a ? 'більше' : 'менше'}.`,
    rozviazok: `Пряма пропорційність: ${a} : ${c} = ${ch(u * a)} : x; x = ${ch(u * a)} · ${c} : ${a} = ${ch(u * c)}.`,
  };
}

