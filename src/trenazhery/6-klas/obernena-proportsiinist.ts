function obernena(r: Vypadok): TrenZavdannia {
  const s = r.vybir(OBERNENI);
  for (;;) {
    const [a, c] = r.rizni(2, 0, s.a.length - 1).map((i) => s.a[i]);
    const b = r.chyslo(s.b[0], s.b[1]);
    const x = (a * b) / c;
    if (!Number.isInteger(x) || x < 1) continue;
    return {
      pytannia: s.umova(a, b, c),
      vidpovid: x,
      odynytsi: s.od,
      pidkazka: `Залежність обернена: друге значення ${c > a ? 'зменшиться' : 'збільшиться'}. ${a} : ${c} = x : ${b}.`,
      rozviazok: `Обернена пропорційність: ${a} : ${c} = x : ${b}; x = ${a} · ${b} : ${c} = ${ch(x)}.`,
    };
  }
}

