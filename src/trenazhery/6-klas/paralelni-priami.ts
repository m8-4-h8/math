// Паралельні прямі (Істер § 45): не перетинаються; через точку поза прямою — лише одна паралельна; дві прямі,
// перпендикулярні до третьої, паралельні; пряма, перпендикулярна до однієї з паралельних, перпендикулярна і до другої;
// дві прямі, паралельні третій, паралельні між собою.
import { type Henerator, type Vypadok, type TrenZavdannia } from '../dopomoha.ts';

const VYDY = ['перпендикулярні', 'паралельні', 'ні те, ні інше'];
const PRIAMI = ['a', 'b', 'c', 'm', 'n', 'k', 'p'];

const ZHYTTIA = [
  { p: 'два сусідні краї аркуша паперу', v: 'перпендикулярні', ch: 'Краї аркуша сходяться під прямим кутом.' },
  { p: 'дві рейки залізниці на рівній ділянці', v: 'паралельні', ch: 'Рейки ніколи не перетинаються.' },
  { p: 'протилежні краї зошита', v: 'паралельні', ch: 'Протилежні краї не перетинаються.' },
  { p: 'ніжка стола і підлога', v: 'перпендикулярні', ch: 'Ніжка стоїть під прямим кутом до підлоги.' },
  { p: 'стрілки годинника о 3:00', v: 'перпендикулярні', ch: 'О 3:00 між стрілками 90°.' },
  { p: 'стрілки годинника о 2:00', v: 'ні те, ні інше', ch: 'О 2:00 між стрілками 60° — перетинаються, але не під прямим кутом.' },
  { p: 'дві сходинки драбини', v: 'паралельні', ch: 'Сходинки розміщені одна над одною і не перетинаються.' },
  { p: 'два сусідні рядки в зошиті', v: 'паралельні', ch: 'Рядки йдуть поруч і не перетинаються.' },
  { p: 'дві струни гітари', v: 'паралельні', ch: 'Струни натягнуті поруч і не перетинаються.' },
  { p: 'лінії букви «Х»', v: 'ні те, ні інше', ch: 'Лінії букви «Х» перетинаються під гострим і тупим кутами.' },
];

function zhyttia(r: Vypadok): TrenZavdannia {
  const z = r.vybir(ZHYTTIA);
  return {
    pytannia: `Які лінії утворюють ${z.p}?`,
    vidpovid: z.v,
    varianty: VYDY,
    pidkazka: 'Чи перетинаються вони? Якщо так — під яким кутом?',
    rozviazok: z.ch,
  };
}

function zaKutom(r: Vypadok): TrenZavdannia {
  const [m, n] = r.rizni(2, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  const typ = r.chyslo(0, 2);
  if (typ === 0) {
    return {
      pytannia: `Прямі $${m}$ і $${n}$ лежать в одній площині і не мають спільних точок. Які вони?`,
      vidpovid: 'паралельні',
      varianty: VYDY,
      pidkazka: 'Не мають спільних точок — отже, не перетинаються.',
      rozviazok: 'Прямі, які лежать в одній площині й не перетинаються, — паралельні.',
    };
  }
  const g = typ === 1 ? 90 : r.krim(20, 160, [90]);
  return {
    pytannia: `Прямі $${m}$ і $${n}$ перетинаються під кутом ${g}°. Які вони?`,
    vidpovid: g === 90 ? 'перпендикулярні' : 'ні те, ні інше',
    varianty: VYDY,
    pidkazka: 'Паралельні прямі не перетинаються; перпендикулярні перетинаються під кутом 90°.',
    rozviazok: g === 90 ? 'Кут 90° — прямі перпендикулярні.' : `Кут ${g}° не прямий, а паралельні прямі взагалі не перетинаються — ні те, ні інше.`,
  };
}

function lohika(r: Vypadok): TrenZavdannia {
  const [a, b, c] = r.rizni(3, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  const L = r.vybir([
    { u: `Прямі $${a}$ і $${b}$ паралельні, а пряма $${c}$ перпендикулярна до $${a}$.`, v: 'перпендикулярні', ch: `Пряма, перпендикулярна до однієї з паралельних, перпендикулярна і до другої.`, pyt: [c, b] },
    { u: `Прямі $${a}$ і $${b}$ обидві перпендикулярні до прямої $${c}$.`, v: 'паралельні', ch: `Дві прямі, перпендикулярні до третьої, паралельні.`, pyt: [a, b] },
    { u: `Відомо, що $${a} \\perp ${b}$ і $${b} \\perp ${c}$.`, v: 'паралельні', ch: `${a} і ${c} обидві перпендикулярні до ${b} — отже, паралельні.`, pyt: [a, c] },
    { u: `Пряма $${a}$ паралельна $${b}$, а $${b}$ паралельна $${c}$.`, v: 'паралельні', ch: `Дві прямі, паралельні третій, паралельні між собою.`, pyt: [a, c] },
    { u: `Пряма $${a}$ перпендикулярна до $${b}$, а $${b}$ паралельна $${c}$.`, v: 'перпендикулярні', ch: `${b} і ${c} паралельні, а ${a} перпендикулярна до однієї з них — отже, і до другої.`, pyt: [a, c] },
  ]);
  const [p, q] = L.pyt;
  return {
    pytannia: `${L.u} Як розміщені прямі $${p}$ і $${q}$?`,
    vidpovid: L.v,
    varianty: VYDY.slice(0, 2),
    pidkazka: 'Намалюй прямі на клітинках: горизонтальні й вертикальні.',
    rozviazok: L.ch,
  };
}

const SKILKY = [
  { p: 'Скільки прямих, паралельних прямій {a}, можна провести через точку M, що не лежить на {a}?', v: '1', ch: 'Лише одну — це властивість паралельних прямих.' },
  { p: 'Скільки спільних точок мають дві паралельні прямі?', v: '0', ch: 'Жодної — паралельні прямі не перетинаються.' },
  { p: 'Скільки прямих, що перетинають пряму {a}, можна провести через точку M, яка не лежить на {a}?', v: 'безліч', ch: 'Будь-яка пряма через M, крім паралельної, перетне {a} — їх безліч.' },
  { p: 'Скільки прямих, перпендикулярних до прямої {a}, можна провести через точку M?', v: '1', ch: 'Лише одну.' },
];

function skilky(r: Vypadok): TrenZavdannia {
  const a = r.vybir(PRIAMI);
  const s = r.vybir(SKILKY);
  return {
    pytannia: s.p.replaceAll('{a}', a),
    vidpovid: s.v,
    varianty: ['0', '1', '2', 'безліч'],
    pidkazka: 'Намалюй пряму і точку і спробуй провести різні прямі.',
    rozviazok: s.ch.replaceAll('{a}', a),
  };
}

export default {
  rivni: ['паралельні, перпендикулярні чи ні те, ні інше', 'дві прямі і третя', 'скільки прямих можна провести'],
  zavdannia(r, riven) {
    if (riven === 1) return r.shans() ? zhyttia(r) : zaKutom(r);
    if (riven === 2) return r.vybir([lohika, lohika, zaKutom])(r);
    return r.vybir([skilky, skilky, lohika])(r);
  },
} satisfies Henerator;
