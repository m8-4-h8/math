// Перпендикулярні й паралельні прямі: перпендикулярні перетинаються під прямим кутом (усі чотири кути
// по 90°); паралельні не перетинаються; через точку поза прямою — одна паралельна й одна перпендикулярна;
// дві прямі, перпендикулярні до третьої, паралельні; суміжні кути при перетині — у сумі 180°.
import { type Henerator, type Vypadok, type TrenZavdannia } from '../dopomoha.ts';

const VYDY = ['перпендикулярні', 'паралельні', 'ні те, ні інше'];
const PRIAMI = ['a', 'b', 'c', 'm', 'n', 'k', 'p'];

const ZHYTTIA = [
  { p: 'Які прямі утворюють два сусідні краї аркуша паперу?', v: 'перпендикулярні', ch: 'Краї аркуша сходяться під прямим кутом.' },
  { p: 'Які прямі утворюють дві рейки залізниці на рівній ділянці?', v: 'паралельні', ch: 'Рейки ніколи не перетинаються.' },
  { p: 'Які прямі утворюють протилежні краї зошита?', v: 'паралельні', ch: 'Протилежні краї не перетинаються.' },
  { p: 'Які прямі утворюють ніжка стола і підлога?', v: 'перпендикулярні', ch: 'Ніжка стоїть під прямим кутом до підлоги.' },
  { p: 'Які прямі утворюють стрілки годинника о 3:00?', v: 'перпендикулярні', ch: 'О 3:00 між стрілками 90°.' },
  { p: 'Які прямі утворюють стрілки годинника о 2:00?', v: 'ні те, ні інше', ch: 'О 2:00 між стрілками 60° — перетинаються, але не під прямим кутом.' },
  { p: 'Які прямі утворюють сходинки драбини?', v: 'паралельні', ch: 'Сходинки розміщені одна над одною і не перетинаються.' },
];

function zhyttia(r: Vypadok): TrenZavdannia {
  const z = r.vybir(ZHYTTIA);
  return { pytannia: z.p, vidpovid: z.v, varianty: VYDY, pidkazka: 'Чи перетинаються вони? Якщо так — під яким кутом?', rozviazok: z.ch };
}

function zaKutom(r: Vypadok): TrenZavdannia {
  const [m, n] = r.rizni(2, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  const g = r.shans(0.4) ? 90 : r.krim(20, 160, [90]);
  return {
    pytannia: `Прямі ${m} і ${n} перетинаються під кутом ${g}°. Які вони?`,
    vidpovid: g === 90 ? 'перпендикулярні' : 'ні те, ні інше',
    varianty: VYDY,
    pidkazka: 'Перпендикулярні — коли кут між ними прямий, 90°.',
    rozviazok: g === 90 ? 'Кут 90° — прямі перпендикулярні.' : `Кут ${g}° не прямий, а паралельні прямі взагалі не перетинаються — ні те, ні інше.`,
  };
}

function lohika(r: Vypadok): TrenZavdannia {
  const [a, b, c] = r.rizni(3, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  const L = r.vybir([
    { u: `Прямі ${a} і ${b} паралельні, а пряма ${c} перпендикулярна до ${a}.`, v: 'перпендикулярні', ch: `Пряма, перпендикулярна до однієї з паралельних, перпендикулярна і до другої.` },
    { u: `Прямі ${a} і ${b} обидві перпендикулярні до прямої ${c}.`, v: 'паралельні', ch: `Дві прямі, перпендикулярні до третьої, паралельні.`, pyt: [a, b] },
    { u: `Пряма ${a} паралельна ${b}, а ${b} паралельна ${c}.`, v: 'паралельні', ch: `Дві прямі, паралельні третій, паралельні між собою.`, pyt: [a, c] },
    { u: `Пряма ${a} перпендикулярна до ${b}, а ${b} паралельна ${c}.`, v: 'перпендикулярні', ch: `${b} і ${c} паралельні, а ${a} перпендикулярна до однієї з них — отже, і до другої.`, pyt: [a, c] },
  ]);
  const [p, q] = L.pyt ?? [c, b];
  return {
    pytannia: `${L.u} Як розміщені прямі ${p} і ${q}?`,
    vidpovid: L.v,
    varianty: VYDY.slice(0, 2),
    pidkazka: 'Намалюй прямі на клітинках.',
    rozviazok: L.ch,
  };
}

function kuty(r: Vypadok): TrenZavdannia {
  const [m, n] = r.rizni(2, 0, PRIAMI.length - 1).map((i) => PRIAMI[i]);
  if (r.shans(0.25)) {
    return {
      pytannia: `Прямі ${m} і ${n} перпендикулярні. Скільки градусів має кожен із чотирьох кутів, що утворилися?`,
      vidpovid: 90,
      odynytsi: '°',
      pidkazka: 'Перпендикулярні прямі утворюють чотири однакові кути.',
      rozviazok: '360° : 4 = 90° — усі кути прямі.',
    };
  }
  const g = r.krim(20, 160, [90]);
  return {
    pytannia: `Прямі ${m} і ${n} перетинаються, один із кутів між ними ${g}°. Знайди сусідній із ним кут.`,
    vidpovid: 180 - g,
    odynytsi: '°',
    pidkazka: 'Сусідні кути при перетині разом утворюють розгорнутий кут — 180°.',
    rozviazok: `180° − ${g}° = ${180 - g}°`,
  };
}

const SKILKY = [
  { p: 'Скільки прямих, паралельних прямій {a}, можна провести через точку M, що не лежить на {a}?', v: '1', ch: 'Лише одну — це властивість паралельних прямих.' },
  { p: 'Скільки прямих, перпендикулярних до прямої {a}, можна провести через точку M, що не лежить на {a}?', v: '1', ch: 'Лише одну.' },
  { p: 'Скільки прямих, перпендикулярних до прямої {a}, можна провести через точку M, що лежить на {a}?', v: '1', ch: 'Лише одну.' },
  { p: 'Скільки прямих, що перетинають пряму {a}, можна провести через точку M, яка не лежить на {a}?', v: 'безліч', ch: 'Будь-яка пряма через M, крім паралельної, перетне {a} — їх безліч.' },
];

function skilky(r: Vypadok): TrenZavdannia {
  const a = r.vybir(PRIAMI);
  const s = r.vybir(SKILKY);
  return {
    pytannia: s.p.replaceAll('{a}', a),
    vidpovid: s.v,
    varianty: ['0', '1', '2', 'безліч'],
    pidkazka: 'Намалюй пряму і точку і спробуй провести різні прямі.',
    rozviazok: s.ch.replaceAll('{a}', a),
  };
}

export default {
  rivni: ['перпендикулярні чи паралельні', 'властивості і кути', 'скільки прямих можна провести'],
  zavdannia(r, riven) {
    if (riven === 1) return r.shans() ? zhyttia(r) : zaKutom(r);
    if (riven === 2) return r.vybir([lohika, lohika, kuty])(r);
    return r.vybir([skilky, lohika, kuty])(r);
  },
} satisfies Henerator;
