// Точка C на відрізку AB: AB = AC + CB. Довжини в міліметрах, показуємо в сантиметрах.
function vidrizok(r: Vypadok): TrenZavdannia {
  const [A, B, C] = r.vybir(TRIIKY);
  const desiati = r.shans(0.4);
  const krok = desiati ? 1 : 10;
  const ab = r.chyslo(4, 20) * 10 + (desiati ? r.chyslo(1, 9) : 0);
  const ac = r.chyslo(1, Math.floor((ab - 10) / krok)) * krok;
  const cb = ab - ac;
  const sm = (mm: number) => des(mm, 1);
  if (r.shans()) {
    return {
      pytannia: `Точка ${C} лежить на відрізку ${A}${B}, ${A}${B} = ${sm(ab)} см, ${A}${C} = ${sm(ac)} см. Знайди ${C}${B}.`,
      vidpovid: sm(cb),
      odynytsi: 'см',
      pidkazka: `За аксіомою вимірювання ${A}${B} = ${A}${C} + ${C}${B}.`,
      rozviazok: `${A}${B} = ${A}${C} + ${C}${B}, тому ${C}${B} дорівнює ${sm(ab)} − ${sm(ac)} = ${sm(cb)} (см).`,
    };
  }
  return {
    pytannia: `Точка ${C} лежить на відрізку ${A}${B}, ${A}${C} = ${sm(ac)} см, ${C}${B} = ${sm(cb)} см. Знайди ${A}${B}.`,
    vidpovid: sm(ab),
    odynytsi: 'см',
    pidkazka: 'Довжина відрізка дорівнює сумі довжин його частин.',
    rozviazok: `${A}${B} = ${A}${C} + ${C}${B}, тобто ${sm(ac)} + ${sm(cb)} = ${sm(ab)} (см).`,
  };
}

// Промінь OC між сторонами кута AOB або бісектриса.
