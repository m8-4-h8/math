// Квадрат: периметр і сторона, половина діагоналі, кути 45° і 90°, «родина» паралелограма (квадрат — і прямокутник,
// і ромб), кут з точкою на стороні, квадрат, розрізаний на смужки, прямокутник із двох квадратів.
import type { Henerator, Vypadok, TrenZavdannia } from '../dopomoha.ts';
import { chotyrykutnyk } from '../chotyrykutnyky.ts';

const TN = ['Так', 'Ні'];
const LITERY: [string, string, string, string][] = [
  ['A', 'B', 'C', 'D'],
  ['K', 'L', 'M', 'N'],
  ['M', 'N', 'P', 'K'],
  ['P', 'Q', 'R', 'S'],
];
const nazva = (l: string[]) => l.join('');

function perymetr(r: Vypadok): TrenZavdannia {
  const l = r.vybir(LITERY);
  const a = r.chyslo(2, 30);
  if (r.shans()) {
    return {
      pytannia: `Сторона квадрата ${nazva(l)} дорівнює ${a} см. Знайди його периметр.`,
      vidpovid: 4 * a,
      odynytsi: 'см',
      pidkazka: 'У квадрата чотири рівні сторони.',
      rozviazok: `P = 4 · ${a} = ${4 * a} см.`,
    };
  }
  return {
    pytannia: `Периметр квадрата ${nazva(l)} дорівнює ${4 * a} см. Знайди сторону ${l[2]}${l[3]}.`,
    vidpovid: a,
    odynytsi: 'см',
    pidkazka: 'Усі чотири сторони квадрата рівні.',
    rozviazok: `${4 * a} : 4 = ${a} см.`,
  };
}

function polovyna(r: Vypadok): TrenZavdannia {
  const l = r.vybir(LITERY);
  const h = r.chyslo(2, 20);
  if (r.shans()) {
    return {
      pytannia: `Діагоналі квадрата ${nazva(l)} перетинаються в точці O, ${l[0]}${l[2]} = ${2 * h} см. Знайди O${l[3]}.`,
      vidpovid: h,
      odynytsi: 'см',
      pidkazka: 'Діагоналі квадрата рівні й діляться навпіл.',
      rozviazok: `${l[1]}${l[3]} дорівнює ${2 * h} см, а O${l[3]} — його половина: ${2 * h} : 2 = ${h} см.`,
    };
  }
  return {
    pytannia: `Діагоналі квадрата ${nazva(l)} перетинаються в точці O, ${l[0]}O = ${h} см. Знайди ${l[1]}${l[3]}.`,
    vidpovid: 2 * h,
    odynytsi: 'см',
    pidkazka: `${l[0]}O — половина діагоналі ${l[0]}${l[2]}, а діагоналі квадрата рівні.`,
    rozviazok: `${l[0]}${l[2]} = 2 · ${h} = ${2 * h} см, і ${l[1]}${l[3]} теж ${2 * h} см.`,
  };
}

/** Кути 45° і 90°: за малюнком. */
function kuty(r: Vypadok): TrenZavdannia {
  const l = r.vybir(LITERY);
  const vypadky: [string, number, string][] = [
    [`O${l[0]}${l[1]}`, 45, `Діагональ ділить прямий кут ${l[0]} навпіл: 90° : 2 = 45°.`],
    [`${l[1]}${l[0]}${l[2]}`, 45, `Діагональ ${l[0]}${l[2]} ділить прямий кут ${l[0]} навпіл: 90° : 2 = 45°.`],
    [`${l[2]}${l[1]}${l[3]}`, 45, `Діагональ ${l[1]}${l[3]} ділить прямий кут ${l[1]} навпіл: 90° : 2 = 45°.`],
    [`${l[0]}O${l[1]}`, 90, 'Діагоналі квадрата перпендикулярні, як у ромба.'],
    [`${l[1]}O${l[2]}`, 90, 'Діагоналі квадрата перпендикулярні, як у ромба.'],
    [`O${l[3]}${l[2]}`, 45, `Діагональ ${l[1]}${l[3]} ділить прямий кут ${l[3]} навпіл: 90° : 2 = 45°.`],
  ];
  const [kut, vidp, poiasn] = r.vybir(vypadky);
  return {
    pytannia: `${nazva(l)} — квадрат, O — точка перетину діагоналей. Знайди ∠${kut}.`,
    malunok: chotyrykutnyk({ forma: 'kvadrat', bukvy: l, peretyn: 'O', W: 220, H: 200 }),
    vidpovid: vidp,
    odynytsi: '°',
    pidkazka: 'Квадрат — і прямокутник, і ромб: діагоналі рівні, перпендикулярні й ділять кути навпіл.',
    rozviazok: poiasn,
  };
}

function tverdzhennia(r: Vypadok): TrenZavdannia {
  const vypadky: [string, boolean, string][] = [
    ['Квадрат — це прямокутник.', true, 'У квадрата всі кути прямі.'],
    ['Квадрат — це ромб.', true, 'У квадрата всі сторони рівні.'],
    ['Будь-який прямокутник — квадрат.', false, 'Сусідні сторони прямокутника можуть бути різними.'],
    ['Будь-який ромб — квадрат.', false, 'Кути ромба можуть бути не прямими.'],
    ['Ромб з прямим кутом — квадрат.', true, 'Сусідні кути разом 180°, тож усі кути прямі, а сторони вже рівні.'],
    ['Ромб з рівними діагоналями — квадрат.', true, 'Паралелограм з рівними діагоналями — прямокутник, а з рівними сторонами — квадрат.'],
    ['Прямокутник з перпендикулярними діагоналями — квадрат.', true, 'Паралелограм з перпендикулярними діагоналями — ромб, а ромб з прямими кутами — квадрат.'],
    ['Чотирикутник з рівними й перпендикулярними діагоналями — квадрат.', false, 'Діагоналі мають ще й ділитися навпіл. Інакше це може бути «повітряний змій».'],
    ['Діагональ квадрата дорівнює його стороні.', false, 'Діагональ — гіпотенуза прямокутного трикутника, вона довша за сторону.'],
    ['Діагоналі квадрата ділять його кути навпіл.', true, 'Квадрат — ромб, а діагоналі ромба ділять кути навпіл.'],
  ];
  const [tekst, tak, poiasn] = r.vybir(vypadky);
  return {
    pytannia: `Чи правильне твердження? ${tekst}`,
    vidpovid: tak ? 'Так' : 'Ні',
    varianty: TN,
    pidkazka: 'Квадрат — найменший «член родини»: він і прямокутник, і ромб.',
    rozviazok: `${tak ? 'Так' : 'Ні'}. ${poiasn}`,
  };
}

/** Точка K на стороні BC, ∠BAK = g: ∠KAC = 45 − g або ∠AKC = 90 + g. */
function tochkaNaStoroni(r: Vypadok): TrenZavdannia {
  const l = r.vybir(LITERY);
  const g = r.chyslo(5, 40);
  if (r.shans()) {
    return {
      pytannia: `У квадраті ${nazva(l)} точка T лежить на стороні ${l[1]}${l[2]}, ∠${l[1]}${l[0]}T = ${g}°. Знайди ∠T${l[0]}${l[2]}.`,
      vidpovid: 45 - g,
      odynytsi: '°',
      pidkazka: `Діагональ ${l[0]}${l[2]} утворює зі стороною ${l[0]}${l[1]} кут 45°.`,
      rozviazok: `Кут ${l[1]}${l[0]}${l[2]} дорівнює 45°, тож кут T${l[0]}${l[2]} дорівнює 45° − ${g}° = ${45 - g}°.`,
    };
  }
  return {
    pytannia: `У квадраті ${nazva(l)} точка T лежить на стороні ${l[1]}${l[2]}, ∠${l[1]}${l[0]}T = ${g}°. Знайди ∠${l[0]}T${l[2]}.`,
    vidpovid: 90 + g,
    odynytsi: '°',
    pidkazka: `Трикутник ${l[0]}${l[1]}T прямокутний. Кути ${l[0]}T${l[1]} і ${l[0]}T${l[2]} суміжні.`,
    rozviazok: `Кут ${l[0]}T${l[1]} дорівнює 90° − ${g}° = ${90 - g}°, а суміжний з ним кут ${l[0]}T${l[2]} дорівнює 180° − ${90 - g}° = ${90 + g}°.`,
  };
}

/** Квадрат розрізали на n однакових смужок з периметром P: сторона a = nt, P = 2(a + t). */
function smuzhky(r: Vypadok): TrenZavdannia {
  const n = r.chyslo(2, 4);
  const t = r.chyslo(1, 6);
  const a = n * t;
  const P = 2 * (a + t);
  const skilky = ['', '', 'два', 'три', 'чотири'][n];
  return {
    pytannia: `Квадрат розрізали на ${skilky} однакові прямокутники-смужки, периметр кожного — ${P} см. Знайди сторону квадрата.`,
    vidpovid: a,
    odynytsi: 'см',
    pidkazka: `Сторони смужки — a і a/${n}, де a — сторона квадрата.`,
    rozviazok: `Периметр смужки 2(a + a/${n}), тож a + a/${n} = ${P / 2}. Звідси a = ${a} см. Перевірка: 2 · (${a} + ${t}) = ${P}.`,
  };
}

/** Два квадрати поруч утворюють прямокутник: його периметр — 6 сторін квадрата. */
function dvaKvadraty(r: Vypadok): TrenZavdannia {
  const a = r.chyslo(2, 15);
  if (r.shans()) {
    return {
      pytannia: `Два однакові квадрати зі стороною ${a} см приклали один до одного так, що вийшов прямокутник. Знайди його периметр.`,
      vidpovid: 6 * a,
      odynytsi: 'см',
      pidkazka: `Сторони прямокутника — ${a} см і 2 · ${a} см.`,
      rozviazok: `P = 2 · (${a} + ${2 * a}) = ${6 * a} см — це шість сторін квадрата.`,
    };
  }
  return {
    pytannia: `Два однакові квадрати приклали один до одного так, що вийшов прямокутник з периметром ${6 * a} см. Знайди периметр одного квадрата.`,
    vidpovid: 4 * a,
    odynytsi: 'см',
    pidkazka: 'Периметр прямокутника — шість сторін квадрата.',
    rozviazok: `Сторона квадрата ${6 * a} : 6 = ${a} см, периметр квадрата 4 · ${a} = ${4 * a} см.`,
  };
}

export default {
  rivni: ['сторони, діагоналі, кути', 'родина паралелограма', 'задачі'],
  zavdannia(r, riven) {
    if (riven === 1) return r.vybir([perymetr, polovyna, kuty])(r);
    if (riven === 2) return r.vybir([tverdzhennia, tverdzhennia, tochkaNaStoroni, kuty])(r);
    return r.vybir([tochkaNaStoroni, smuzhky, dvaKvadraty, polovyna])(r);
  },
} satisfies Henerator;
